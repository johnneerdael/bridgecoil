#!/usr/bin/env python3
"""List every screenshot the user guide still needs, for the next capture run.

A page marks one with an admonition:

    !!! screenshot "tools-overview.png"
        Tools, on a connected TV. All 11 tools on one page.

Writes docs/user-guide/_meta/screenshots.md. With --check, fails if that file is out of date, if
two pages claim one file name, or if a placeholder doesn't say what to capture.
"""
from pathlib import Path
import argparse
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
GUIDE = ROOT / "docs/user-guide"
OUTPUT = GUIDE / "_meta/screenshots.md"
PLACEHOLDER = re.compile(r'^!!! screenshot "([a-z0-9-]+\.png)"\n((?:    .*\n|\n)+)', re.M)


def collect():
    shots, errors, seen = [], [], {}
    for page in sorted(GUIDE.rglob("*.md")):
        relative = page.relative_to(GUIDE)
        if relative.parts[0] in ("_meta", "_snippets"):
            continue
        text = page.read_text()
        for name, body in PLACEHOLDER.findall(text):
            what = " ".join(line.strip() for line in body.splitlines()).strip()
            if name in seen:
                errors.append(f"{relative}: {name} is already used by {seen[name]}")
            seen[name] = relative
            if not what:
                errors.append(f"{relative}: {name} doesn't say what to capture")
            shots.append((relative, name, what))
    return shots, errors


def render(shots):
    lines = [
        "# Screenshots still to capture",
        "",
        "Generated by `scripts/docs-shots.py` from the placeholders in the guide. Not published.",
        "",
        f"{len(shots)} shots. Capture each from the current build, save it to",
        "`docs/user-guide/assets/shots/`, and replace its placeholder with the image.",
        "",
        "| Page | File | What to capture |",
        "|---|---|---|",
    ]
    lines += [f"| `{page}` | `{name}` | {what} |" for page, name, what in shots]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    shots, errors = collect()
    if errors:
        raise SystemExit("\n".join(errors))
    text = render(shots)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit("The shot list is out of date. Run python3 scripts/docs-shots.py")
    else:
        OUTPUT.write_text(text)
    print(f"{len(shots)} screenshots to capture")


if __name__ == "__main__":
    sys.exit(main())
